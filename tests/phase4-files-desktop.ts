  await page.locator(".ws-row").filter({ hasText: "README.md" }).click(); await page.getByTestId("undo-file").click();
  await expect.poll(async () => (await readFile(join(workspace, "README.md"))).equals(original)).toBe(true);
  await page.screenshot({ path: join(artifacts, "undo-en.png") });
  console.log("[phase4-files] failed submission and stale preview keep the write pending");
  await page.goto("app://codeharness/");
  await page.locator("#task").fill("demo edit README.md: before => refreshed"); await page.locator("button[type=submit]").click();
  await expect(card).toBeVisible();
  await page.route("**/interrupts/*", route => route.fulfill({ status: 503, body: "Unavailable" }));
  await card.getByTestId("approval-approve").click(); await expect(card.locator("[role=alert]")).toBeVisible();
  assert.deepEqual(await readFile(join(workspace, "README.md")), original);
  await page.unroute("**/interrupts/*");
  await writeFile(join(workspace, "README.md"), Buffer.concat([original, Buffer.from("# external\r\n")]));
  await card.getByTestId("approval-approve").click(); await expect(card.locator("[role=alert]")).toBeVisible();
  await card.getByRole("button", { name: "Refresh review", exact: true }).click();
  await card.getByTestId("approval-approve").click(); await expect(page.locator(".stop")).toBeDisabled();
  assert.ok((await readFile(join(workspace, "README.md"), "utf8")).includes("refreshed"));
  await writeFile(join(workspace, "README.md"), original);
