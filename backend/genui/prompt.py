"""The tool description: a short preamble plus the generated library prompt, bounded.

The library half is generated by `npm run generate:genui`; this module only adds the rules the
model cannot infer from the signatures, and refuses to grow past the budget.
"""

from __future__ import annotations

from pathlib import Path

PROMPT_PATH = Path(__file__).resolve().parents[1] / "agent" / "genui_prompt.txt"
MAX_PROMPT = 8_000

PREAMBLE = (
    "Call render_ui with one program built only from the components below. "
    "Use only ids that appear in this run's tool results. "
    "Never repeat the program in your answer: the rendered interface is the answer, "
    "and a short sentence may accompany it. "
    "Never put a key, a token or a secret inside a string. "
    "If the tool rejects the program, fix the line it names or answer in plain text."
)


def render_prompt() -> str:
    """The description of `render_ui`, never longer than `MAX_PROMPT` characters."""
    try:
        library = PROMPT_PATH.read_text(encoding="utf-8").strip()
    except OSError:
        return PREAMBLE
    return f"{PREAMBLE}\n\n{library}"[:MAX_PROMPT]
